-- Walmart tab: Walmart Marketplace onboarding, one row per store.
--   Stages: Awaiting App -> Payment Setup -> Account Created (done), plus Exempted.
--   The store's Walmart status under Delivery Platforms follows the stage:
--     Awaiting App / Payment Setup -> Work in Progress · Account Created -> Onboarded · Exempted -> Exempted
--
-- The tab starts empty; stores are added by importing Walmart's report (Marwaha rows only).
-- Older Walmart records on the Onboarding tab are left in the database but no longer shown.
--
-- Run once in Supabase (SQL Editor -> New query -> paste -> Run). It can safely be run again.
-- Until it is run, the Walmart tab shows a reminder and other tabs work as before.

create table if not exists public.walmart (
  id bigint generated by default as identity primary key,
  store_num text not null unique,
  stage text not null default 'Awaiting App',
  notes text not null default '',
  history jsonb not null default '[]'::jsonb,
  last_email_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

do $$
begin
  if not exists (select 1 from pg_constraint where conrelid = 'public.walmart'::regclass and conname = 'walmart_stage_check') then
    alter table public.walmart add constraint walmart_stage_check
      check (stage in ('Awaiting App', 'Payment Setup', 'Account Created', 'Exempted'));
  end if;
end $$;

-- Same access as the tracker's other tables: the app reads and writes with the project's publishable key.
alter table public.walmart enable row level security;
drop policy if exists walmart_all on public.walmart;
create policy walmart_all on public.walmart for all to anon, authenticated using (true) with check (true);
grant select, insert, update, delete on public.walmart to anon, authenticated;
