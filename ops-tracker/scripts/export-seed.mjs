// Prints SQL that loads the dummy dataset into a Supabase project created
// with supabase/schema.sql:
//   node scripts/export-seed.mjs > supabase/seed.sql
// Demo users get fixed UUIDs. To sign in as one, create an auth user with the
// same id in Supabase Auth (or update profiles.id after inviting yourself).
import { generateDataset } from "../src/data/mockData.js";
import { toISODate } from "../src/lib/dates.js";

const now = new Date();
const ds = generateDataset(toISODate(now), now);
const uuid = (userId) => `00000000-0000-4000-8000-${String(userId.replace(/\D/g, "")).padStart(12, "0")}`;
const q = (v) => (v == null || v === "" ? "null" : typeof v === "number" || typeof v === "boolean" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const insert = (table, cols, rows) => {
  if (!rows.length) return "";
  const out = [];
  for (let i = 0; i < rows.length; i += 500) {
    out.push(`insert into ${table} (${cols.join(", ")}) values\n${rows.slice(i, i + 500).map((r) => `(${r.map(q).join(", ")})`).join(",\n")}\non conflict do nothing;`);
  }
  return out.join("\n");
};

const sql = [
  "-- Generated by scripts/export-seed.mjs. Dummy data only.",
  "begin;",
  "-- Auth users must exist first (profiles.id references auth.users).",
  insert("auth.users", ["id", "email", "aud", "role"], ds.users.map((u) => [uuid(u.id), u.email, "authenticated", "authenticated"])),
  insert("profiles", ["id", "full_name", "email", "role", "region", "status", "last_active_at"], ds.users.map((u) => [uuid(u.id), u.name, u.email, u.role, u.region, u.status, u.lastActive])),
  insert("platform_settings", ["platform_id", "enabled", "connection", "sync_minutes", "error_rate_threshold", "min_rating", "downtime_min_threshold", "alert_on_pause", "alert_email", "merchant_portal_url", "last_sync_at"],
    ds.platformSettings.map((p) => [p.id, p.enabled, p.connection, p.syncMinutes, p.thresholds.errorRate, p.thresholds.minRating, p.thresholds.downtimeMin, p.alertOnPause, p.alertEmail, p.merchantPortal, p.lastSync])),
  insert("stores", ["id", "store_number", "name", "city", "state", "region", "franchisee", "fbc_id", "area_coach_id", "om_id", "phone", "address", "opened_year"],
    ds.stores.map((s) => [s.id, s.number, s.name, s.city, s.state, s.region, s.franchisee, uuid(s.fbcId), uuid(s.areaCoachId), uuid(s.omId), s.phone, s.address, s.openedYear])),
  insert("store_platforms", ["store_id", "platform_id", "status", "external_id"], ds.connections.map((c) => [c.storeId, c.platformId, c.status, c.externalId])),
  insert("daily_metrics", ["store_id", "platform_id", "date", "orders", "sales", "error_orders", "cancellations", "rating_sum", "rating_count", "downtime_min", "prep_min_sum"],
    ds.metrics.map((m) => [m.storeId, m.platformId, m.date, m.orders, m.sales, m.errorOrders, m.cancellations, m.ratingSum, m.ratingCount, m.downtimeMin, m.prepMinSum])),
  insert("issues", ["id", "store_id", "platform_id", "category", "severity", "status", "title", "description", "order_id", "screenshot_url", "reporter_id", "assignee_id", "created_at", "updated_at"],
    ds.issues.map((i) => [i.id, i.storeId, i.platformId, i.category, i.severity, i.status, i.title, i.description, i.orderId, i.screenshot, uuid(i.reporterId), i.assigneeId ? uuid(i.assigneeId) : null, i.createdAt, i.updatedAt])),
  insert("issue_events", ["issue_id", "user_id", "type", "text", "meta", "created_at"],
    ds.issues.flatMap((i) => i.events.map((e) => [i.id, uuid(e.userId), e.type, e.text, e.type === "assigned" && e.meta ? uuid(e.meta) : e.meta ?? null, e.at]))),
  `select setval('issue_number_seq', ${1200 + ds.issues.length + 1});`,
  "commit;",
].join("\n\n");

process.stdout.write(sql + "\n");
